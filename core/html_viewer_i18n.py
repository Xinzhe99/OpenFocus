def normalize_viewer_lang(lang: Optional[str]) -> str:
    """Map an OpenFocus locale tag to one of the 12 viewer language codes."""
    raw = str(lang or "").strip().lower().replace("_", "-")
    if raw in VIEWER_LANG_NAMES:
        return raw
    base = raw.split("-", 1)[0]
    if base in VIEWER_LANG_NAMES:
        return base
    return "en"


