"""Exact HF9 Method C gray-half parity from captured native pixels.

Provenance: F:/REA_heliconfocus9/outputs/c_gray_resize_512_v1,
resize_meta.json, call1_src.npy -> call1_dst_post.npy and
call3_src.npy -> call3_dst_post.npy. Metadata records both source planes as
512x512 (format 33) and their post-call results as 256x256 (format 33);
the arrays are uint16. Calls 5/6 and their dst_pre captures are expansion
calls, so they are not gray-half references.

fixtures/hf9_native_gray_half_strips.npz contains only exact source slices
[0:16, :] and [496:512, :] and captured destination slices [0:6, :] and
[250:256, :], for calls 1 and 3. Expected pixels are copied from those
native post-call captures, never generated by the Python resampler.

At fixed half scale, centers are 2*i + 0.5 and tap support is +/-3.998.
Top local result rows 0:6 have all their in-image taps in source rows 0:16;
rows 6:8 need rows beyond the strip. Bottom local result rows 2:8 match
native rows 250:256; rows 0:2 need pixels preceding source row 496.
The even source offset 496 preserves the sampling phase. Full source width
preserves both real horizontal boundaries, while the retained output rows
exercise the real top/bottom valid-tap boundaries. Variable native pixels
pin the vertical-then-horizontal float/FMA result with exact u16 equality.

Full-pipeline provenance: F:/REA_heliconfocus9/experiments/golden/stacks/
S1_zones/f00.tif, f01.tif, f02.tif, f03.tif (original uint8 grayscale,
all four complete 512x512 frames, in filename order). The expected complete
uint16 512x512 depth plane is the official native sidecar
F:/REA_heliconfocus9/experiments/golden/helicon_dmap/
S1_zones_R22_S5_dmap.tiff, not a Python/reference-generated output.
fixtures/hf9_native_s1_zones_depth.npz preserves these pixels without
cropping: depth recurrences depend on the complete image. This consumer
regression covers votes, sqrt guide, horizontal/vertical guided filtering,
snap-before-expand and final depth quantization together.
The result member is the complete uint8 512x512 official fused output from
F:/REA_heliconfocus9/experiments/golden/mp3/
S1_zones__c3_R22_S5_F0__noalign.tif. It also pins the consumer-visible
Method C reverse full-resolution merge with the original four frames.

Odd-canvas provenance: F:/REA_heliconfocus9/outputs/c_gray_resize_odd_v1/
call6_src.npy (64x65 uint16) -> call6_dst_post.npy (129x131 uint16),
resize_meta.json return RVA 0x40F469. The fixture preserves both complete
captured planes. Native float32 dst/src scale, half-pixel offset and
position/scale + offset must remain separate operations before the FMA
passes; a combined equivalent expression changes 68 destination pixels.
"""
from pathlib import Path

import numpy as np
import pytest

from fusion_methods._hf9_resample import half_gray


_FIXTURE = Path(__file__).parent / 'fixtures' / 'hf9_native_gray_half_strips.npz'


@pytest.mark.parametrize('call', [1, 3])
@pytest.mark.parametrize('edge, result_rows', [('top', slice(0, 6)),
                                              ('bottom', slice(2, 8))])
def test_half_gray_matches_native_capture_strips(call, edge, result_rows):
    with np.load(_FIXTURE, allow_pickle=False) as captured:
        source = captured[f'call{call}_src_{edge}']
        expected = captured[f'call{call}_dst_{edge}']

    assert source.shape == (16, 512)
    assert source.dtype == np.uint16
    assert expected.shape == (6, 256)
    assert expected.dtype == np.uint16

    result = half_gray(source)

    assert result.shape == (8, 256)
    assert result.dtype == np.uint16
    np.testing.assert_array_equal(result[result_rows, :], expected)


def test_method_c_depth_matches_official_s1_zones_sidecar():
    from fusion_methods.openfocus_depth import depth_map

    fixture = Path(__file__).parent / 'fixtures' / 'hf9_native_s1_zones_depth.npz'
    with np.load(fixture, allow_pickle=False) as captured:
        frames = captured['frames']
        expected = captured['depth']

    assert frames.shape == (4, 512, 512)
    assert frames.dtype == np.uint8
    assert expected.shape == (512, 512)
    assert expected.dtype == np.uint16

    result = depth_map(list(frames), None, 45, 5, None, thread_count=1,
                       return_codes=True, half_resolution=True)

    assert result.shape == expected.shape
    assert result.dtype == np.uint16
    np.testing.assert_array_equal(result, expected)


