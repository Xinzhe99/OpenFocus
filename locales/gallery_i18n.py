GALLERY_TRANSLATIONS: dict[str, dict[str, str]] = {
    "en": _EN,
    "zh": _ZH,
    "ja": _JA,
    "es": _ES,
    "de": _DE,
    "fr": _FR,
    "it": _IT,
    "ko": _KO,
    "nl": _NL,
    "pl": _PL,
    "pt": _PT,
    "ru": _RU,
}


def t_gallery(key: str, lang: str | None = None, **kwargs: Any) -> str:
    """Resolve a Gallery/Account i18n string across all 12 OpenFocus languages.

    Delegates to ``locales.trans.t(key)`` when ``lang`` is ``None`` and the key
    is registered in the active ``TranslationManager`` table, falling back to
    ``GALLERY_TRANSLATIONS`` for the active language and then English.
    """
    template: str | None = None
    active_lang = lang

    if active_lang is None:
        try:
            from locales import trans

            active_lang = getattr(trans, "current_lang", "en") or "en"
            loaded = getattr(trans, "_translations", None)
            if isinstance(loaded, Mapping):
                lang_table = loaded.get(active_lang)
                if isinstance(lang_table, Mapping) and key in lang_table:
                    template = lang_table[key]
            else:
                lang_table = getattr(trans, "translations", {}).get(active_lang, {})
                if key in lang_table:
                    template = trans.t(key)
        except Exception:
            active_lang = "en"

    if template is None:
        table = GALLERY_TRANSLATIONS.get(active_lang or "en", {})
        template = table.get(key)
    if template is None:
        template = GALLERY_TRANSLATIONS["en"].get(key, key)

    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, ValueError, IndexError):
            return template
    return template


def translate_tag(tag_key: str, lang: str | None = None) -> str:
    """Translate a canonical AI tag / interest key."""
    return t_gallery(f"gallery_tag_{tag_key}", lang=lang)


def translate_report_reason(reason_key: str, lang: str | None = None) -> str:
    """Translate a canonical report reason key."""
    return t_gallery(f"gallery_report_reason_{reason_key}", lang=lang)


def translate_rejection_reason(reason_key: str, lang: str | None = None) -> str:
    """Translate a canonical content_rejected details.reason key."""
    key = f"gallery_reject_reason_{reason_key}"
    if key in GALLERY_TRANSLATIONS["en"]:
        return t_gallery(key, lang=lang)
    return translate_error(reason_key, lang=lang)


def translate_badge(badge_key: str, lang: str | None = None) -> str:
    """Translate a canonical account/work badge key."""
    return t_gallery(f"gallery_badge_{badge_key}", lang=lang)


def translate_period(period_key: str, lang: str | None = None) -> str:
    """Translate a canonical UTC leaderboard period key (7d, 1m, ...)."""
    return t_gallery(f"gallery_period_{period_key}", lang=lang)


def translate_error(error_code: str, lang: str | None = None) -> str:
    """Translate a canonical API error code to the active UI language."""
    key = f"gallery_err_{error_code}"
    if key in GALLERY_TRANSLATIONS["en"]:
        return t_gallery(key, lang=lang)
    return t_gallery("gallery_err_internal_error", lang=lang)


def _field(item: Any, name: str, default: Any = None) -> Any:
    if isinstance(item, Mapping):
        return item.get(name, default)
    return getattr(item, name, default)


def format_notification(notification: Any, lang: str | None = None) -> str:
    """Render a notification purely from its structured English type & fields.

    Accepts either a dict or dataclass/object with structured fields such as
    ``type`` / ``notification_type``, ``actor`` / ``actor_name`` / ``actors``,
    ``count`` / ``actor_count``, ``work_title``, ``period``, ``rank``,
    ``points``, ``reason``, and ``detail``.
    """
    notif_type = str(
        _field(notification, "type")
        or _field(notification, "notification_type")
        or "system_announcement"
    )
    payload = (
        _field(notification, "params")
        or _field(notification, "payload")
        or _field(notification, "data")
        or {}
    )
    if not isinstance(payload, Mapping):
        payload = {}

    def _get(name: str, default: Any = "") -> Any:
        val = _field(notification, name, None)
        if val is not None and val != "":
            return val
        val = payload.get(name)
        return default if val is None else val

    actors = _get("actors", None)
    actor = _get("actor_nickname", "") or _get("actor_name", "") or _get("actor", "")
    if not actor and isinstance(actors, (list, tuple)) and actors:
        first = actors[0]
        actor = str(first.get("nickname", first) if isinstance(first, Mapping) else first)
    if not actor:
        actor = t_gallery("gallery_author_label", lang=lang)

    count_raw = _get("actor_count", None)
    if count_raw is None:
        count_raw = _get("count", 1)
    try:
        count = max(1, int(count_raw))
    except (TypeError, ValueError):
        count = 1
    others = max(0, count - 1)

    work_title = str(_get("work_title", "") or t_gallery("gallery_untitled_work", lang=lang))
    period_raw = str(_get("period", "7d") or "7d")
    period = (
        translate_period(period_raw, lang=lang)
        if period_raw in LEADERBOARD_PERIOD_KEYS
        else period_raw
    )
    rank = _get("rank", 1)
    points = _get("points", 0)
    reason_raw = str(_get("reason", "") or "policy_violation")
    reason = translate_rejection_reason(reason_raw, lang=lang)
    detail = str(_get("detail", "") or _get("message_key", ""))
    if detail and detail in GALLERY_TRANSLATIONS["en"]:
        detail = t_gallery(detail, lang=lang)

    if notif_type == "work_liked" and others <= 0:
        template_key = "gallery_notif_work_liked_single"
    else:
        template_key = f"gallery_notif_{notif_type}"
        if template_key not in GALLERY_TRANSLATIONS["en"]:
            template_key = "gallery_notif_system_announcement"

    return t_gallery(
        template_key,
        lang=lang,
        actor=actor,
        others=others,
        count=count,
        work_title=work_title,
        period=period,
        rank=rank,
        points=points,
        reason=reason,
        detail=detail or notif_type,
    )
def normalize_lang_code(raw: Any) -> str:
    """Normalize a language/locale code to its lowercase primary subtag."""
    if not isinstance(raw, str):
        return ""
    cleaned = raw.strip().lower().replace("_", "-")
    if not cleaned:
        return ""
    primary = cleaned.split("-", 1)[0]
    if 2 <= len(primary) <= 8 and primary.isascii() and primary.isalpha():
        return primary
    return ""


def current_ui_language(default: str = "en") -> str:
    """Return the active OpenFocus UI language code normalized for Gallery APIs."""
    try:
        from locales import trans

        lang = normalize_lang_code(getattr(trans, "current_lang", default))
        return lang or normalize_lang_code(default) or "en"
    except Exception:
        return normalize_lang_code(default) or "en"


def resolve_comment_translation(
    comment: Any,
    *,
    mode: str = "auto",
    target_lang: str | None = None,
) -> tuple[str, bool]:
    """Return ``(display_text, is_translated)`` for a comment or danmaku item.

    Falls back cleanly to the original ``content`` unless ``mode == 'auto'``,
    ``translated_content`` is non-empty and differs from ``content``, and
    ``translated_lang`` (if specified) matches ``target_lang``.
    """
    original = str(_field(comment, "content", "") or "").strip()
    if mode != "auto" or not original:
        return original, False
    translated = str(_field(comment, "translated_content", "") or "").strip()
    if not translated or translated == original:
        return original, False
    target = normalize_lang_code(target_lang or current_ui_language())
    translated_lang = normalize_lang_code(_field(comment, "translated_lang", ""))
    if translated_lang and target and translated_lang != target:
        return original, False
    return translated, True
